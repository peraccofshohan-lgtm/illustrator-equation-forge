#!/usr/bin/env python3
"""Deterministic standalone JSX packager (no third-party dependencies)."""
from pathlib import Path
root = Path(__file__).resolve().parents[2]
parts = [root / 'src/core/engine.js', root / 'src/ui/app.js']
header = '''/*\n * EquationForge — Ultimate Equation & Scientific Typesetting System\n * Version 0.1.0 | Copyright (c) Shohan Khan\n * Standalone Adobe Illustrator ExtendScript (ES3) application.\n * Generated by scripts/build/build.py; do not edit dist directly.\n */\n'''
text = header + '\n'.join(p.read_text(encoding='utf-8').rstrip() for p in parts) + '\n'
out = root / 'dist/EquationForge.jsx'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(text, encoding='utf-8', newline='\n')
print('Built %s (%d bytes)' % (out.relative_to(root), out.stat().st_size))
